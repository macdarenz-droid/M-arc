// LIB-6 legacy fallback (plan 2.6): a golden-B close-up script, loaded frozen. The script's drawing part is cut where
// its Playwright run starts and imported, exactly as the vendored artifact/howto-layers.mjs loadRenderer() does, so the
// output is the bytes golden B was built from. It runs on a mirror copy of tools/plates/layers/ (the scripts create an
// out/ folder when loaded), so the vendored folder is never written to.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

/** The 8 golden-B close-up scripts, by howto id (artifact/howto-layers.mjs RENDERER). */
export const LEGACY_SCRIPTS = {
  machine_chest_press: 'exercises/machine_chest_press.howto-render.mjs',
  barbell_back_squat: 'exercises/barbell_back_squat.howto-render.mjs',
  leg_press: 'exercises/leg_press.howto-render.mjs',
  dumbbell_lateral_raise: 'howto/render-dumbbell_lateral_raise.mjs',
  hanging_leg_raise: 'howto/render-hanging_leg_raise.mjs',
  lat_pulldown: 'howto/render-lat_pulldown.mjs',
  pull_up: 'howto/render-pull_up.mjs',
  seated_cable_row: 'howto/render-seated_cable_row.mjs',
};
/** What artifact/howto-layers.mjs reads from a close-up script. */
export const API = ['handZoom', 'postureZoom', 'zoomSection', 'chipRow', 'PAGES', 'CSS', 'ZCSS', 'howto'];
export const PLAYWRIGHT_CUT = 'const { chromium } = createRequire(';

/** The script's source with its Playwright run cut off and an `__api` export added (howto-layers.mjs, verbatim logic). */
export function legacySource(layersDir, rel) {
  const file = join(layersDir, rel), url = pathToFileURL(file).href;
  let src = readFileSync(file, 'utf8');
  const cut = src.indexOf(PLAYWRIGHT_CUT);
  if (cut < 0) throw new Error(`${rel}: render script has no Playwright start to cut at`);
  src = src.slice(0, cut)
    .replace(/import\.meta\.url/g, JSON.stringify(url))
    .replace(/(from\s+|import\s*\(\s*)'(\.{1,2}\/[^']+)'/g, (m, pre, spec) => `${pre}'${new URL(spec, url).href}'`);
  return src + `\nexport const __api = { ${API.map(n => `${n}: typeof ${n} === 'undefined' ? undefined : ${n}`).join(', ')} };\n`;
}

/** Load one exercise's frozen close-up script from `layersDir` (a mirror); the generated module goes to `genDir`. */
export async function loadLegacyCloseups(id, layersDir, genDir) {
  const rel = LEGACY_SCRIPTS[id];
  if (!rel) throw new Error(`legacy close-ups: no golden-B script for ${id}`);
  mkdirSync(genDir, { recursive: true });
  const out = join(genDir, `${id}.mjs`);
  writeFileSync(out, `// GENERATED by tools/plates/library/render/legacy.mjs from ${rel} (drawing part only). Do not edit.\n${legacySource(layersDir, rel)}`);
  return (await import(pathToFileURL(out).href)).__api;
}
